'use strict';
const {test}=require('node:test'),a=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const base=path.resolve(process.cwd(),'docs/ari/03/vector_retrieval');
const {evaluate,cosine}=require(path.join(process.cwd(),'scripts/tools/arctor-m0121-score.cjs'));
const protocol=JSON.parse(fs.readFileSync(path.join(base,'M0121_BENCHMARK_PROTOCOL_V1.json'),'utf8'));
const doc=fs.readFileSync(path.join(base,'M0121_BENCHMARK_PROTOCOL_RU.md'),'utf8');
const valid=()=>({contract:'ARCTOR_M0121_PRECOMPUTED_TWO_MODEL_EVAL_V1',goldSha256:'A'.repeat(64),source:'OWNER_SUPPLIED_PRECOMPUTED_REAL_MODEL_OUTPUTS',models:[{id:'a',provenance:'frozen-test-fixture'},{id:'b',provenance:'frozen-test-fixture'}],queries:[{id:'q',locale:'ru',relevantOnIds:['on-1']}],candidates:[{id:'on-1'},{id:'on-2'}],embeddings:{a:{queries:{q:[1,0]},candidates:{'on-1':[1,0],'on-2':[0,1]}},b:{queries:{q:[0,1]},candidates:{'on-1':[1,0],'on-2':[0,1]}}}});
function bad(mod){const v=valid();mod(v);a.throws(()=>evaluate(v),/M0121_SCORE_INVALID_/)}
test('protocol is design only',()=>{a.equal(protocol.state,'PREPARED_NOT_EVALUATED');a.equal(protocol.acceptance,'NOT_ACCEPTED_UNTIL_REAL_MODEL_COMPARISON')});
test('models have two distinct ids',()=>a.notEqual(protocol.models[0].id,protocol.models[1].id));
test('protocol forbids paid calls',()=>a.equal(protocol.security.noEmbeddingCalls,true));
test('protocol preserves ledger',()=>a.equal(protocol.security.ledgerUnchanged,true));
test('doc states Gold limitations',()=>a.match(doc,/27 сценариев/));
test('doc prohibits false model metrics',()=>a.match(doc,/Запрещено утверждать/));
test('cosine equal vectors 1',()=>a.equal(cosine([1,0],[1,0]),1));
test('cosine orthogonal 0',()=>a.equal(cosine([1,0],[0,1]),0));
test('distinct output results',()=>{const r=evaluate(valid());a.equal(r.modelResults.a.recallAt1,1);a.equal(r.modelResults.b.recallAt1,0);a.equal(r.qualityCertified,false)});
test('nDCG differs',()=>{const r=evaluate(valid());a.ok(r.modelResults.a.ndcgAt5>r.modelResults.b.ndcgAt5)});
test('MRR differs',()=>{const r=evaluate(valid());a.ok(r.modelResults.a.mrrAt5>r.modelResults.b.mrrAt5)});
test('per locale partitions',()=>{const r=evaluate(valid());a.equal(r.modelResults.a.perLocale.ru.queries,1)});
test('no auto acceptance',()=>a.equal(evaluate(valid()).acceptance,'PROVISIONAL_REQUIRES_OWNER_EVIDENCE_AND_GOLD_REVIEW'));
test('reject wrong contract',()=>bad(x=>x.contract='other'));
test('reject hash missing',()=>bad(x=>x.goldSha256='bad'));
test('reject source missing',()=>bad(x=>x.source='UNKNOWN'));
test('reject duplicate models',()=>bad(x=>x.models[1].id='a'));
test('reject 3 models',()=>bad(x=>x.models.push({id:'c',provenance:'fixture'})));
test('reject no provenance',()=>bad(x=>x.models[0].provenance=''));
test('reject duplicate queries',()=>bad(x=>x.queries.push(x.queries[0])));
test('reject missing labels',()=>bad(x=>x.queries[0].relevantOnIds=[]));
test('reject missing candidate label',()=>bad(x=>x.queries[0].relevantOnIds=['other']));
test('reject unknown locale',()=>bad(x=>x.queries[0].locale='fr'));
test('reject duplicate candidates',()=>bad(x=>x.candidates.push(x.candidates[0])));
test('reject query vector missing',()=>bad(x=>delete x.embeddings.a.queries.q));
test('reject candidate vector missing',()=>bad(x=>delete x.embeddings.a.candidates['on-2']));
test('reject zero vector',()=>bad(x=>x.embeddings.a.queries.q=[0,0]));
test('reject NaN vector JSON invalid',()=>bad(x=>x.embeddings.a.queries.q=[NaN,0]));
test('reject unequal vector dimension',()=>bad(x=>x.embeddings.a.candidates['on-2']=[0,1,2]));
test('reject vector dimension <2',()=>bad(x=>x.embeddings.a.queries.q=[1]));
test('reject unauthorized extra model embedding',()=>bad(x=>x.embeddings.extra=x.embeddings.a));
test('reject model query ID mismatch',()=>bad(x=>x.embeddings.a.queries.extra=[1,0]));
test('reject model candidate ID mismatch',()=>bad(x=>x.embeddings.a.candidates.extra=[1,0]));
test('no diff required cross-model dimensions',()=>{const x=valid();x.embeddings.b.queries.q=[0,1,0];x.embeddings.b.candidates['on-1']=[1,0,0];x.embeddings.b.candidates['on-2']=[0,1,0];a.equal(evaluate(x).modelResults.b.dimensions,3)});
test('reject missing model payload',()=>bad(x=>delete x.embeddings.b));
test('reject mismatched source labels',()=>bad(x=>x.queries[0].relevantOnIds=[null]));
test('do not claim independent Gold',()=>a.match(doc,/не.*независимого/i));
test('no application SQL',()=>a.equal(protocol.security.noDbWrites,true));
test('lexical fallback kept',()=>a.equal(protocol.security.lexicalOnlyUntilApproved,true));
