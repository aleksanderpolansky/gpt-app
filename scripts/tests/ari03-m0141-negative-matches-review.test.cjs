'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const R=require(process.env.ARCTOR_M0141_RUNNER_PATH||path.join(__dirname,'../ari/M0141_NEGATIVE_MATCH_REVIEW.cjs'));
const hybridPath=process.env.ARCTOR_M0141_HYBRID_PATH||path.join(process.cwd(),'src/lib/ontology-research/hybridRankerV1.ts');
const goldPath=process.env.ARCTOR_M0141_GOLD_PATH||path.join(__dirname,'../ari/M0140_OWNER_APPROVED_EXACT_GOLD_18.json');
const gold=JSON.parse(fs.readFileSync(goldPath,'utf8'));
const H=R.loadHybrid(hybridPath);
const report=R.execute(hybridPath,goldPath);
const keys=R.TOPICS.map(t=>t.key);
const targetId=R.GOLD_WALK;
const check=t=>R.evaluateTopic(gold,H,t);
const unapproved=R.TOPICS.filter(t=>t.key!=='walking');
const canonicalText='Человеческий организм';
const pending=(t,status,kind='alias',locale='ru')=>({onId:R.GOLD_HUMAN_ORGANISM,scope:{kind:'global_system'},locale,kind,text:t.text,...(kind==='alias'?{aliasStatus:status}:{})});
test('contract M0141',()=>assert.equal(R.CONTRACT,'ARCTOR_ARI03_M0141_NEGATIVE_MATCH_REVIEW_V1'));
test('five owner roadmap topics in order',()=>assert.deepEqual(keys,['child','human','shops','guitar','walking']));
test('exact target source Gold validates',()=>assert.equal(R.validateGold(gold),true));
test('18 controlled ON only',()=>assert.equal(gold.candidates.length,18));
test('Walking approved exact id is real',()=>assert.equal(R.ownerApprovedTarget(gold,'Ходьба'),targetId));
test('case-insensitive Walking approved canonical',()=>assert.equal(R.ownerApprovedTarget(gold,'ходьба'),targetId));
test('Human organism distinct from generic human',()=>assert.notEqual(R.ownerApprovedTarget(gold,canonicalText),R.ownerApprovedTarget(gold,'человек')));
test('Human organism title owner-approved',()=>assert.equal(R.ownerApprovedTarget(gold,canonicalText),R.GOLD_HUMAN_ORGANISM));
test('child not owner-approved query',()=>assert.equal(R.ownerApprovedTarget(gold,'ребёнок'),null));
test('shops not owner-approved query',()=>assert.equal(R.ownerApprovedTarget(gold,'магазины'),null));
test('guitar not owner-approved query',()=>assert.equal(R.ownerApprovedTarget(gold,'гитара'),null));
test('walking duration is distinct from Walking',()=>assert.notEqual(R.GOLD_WALK_DURATION,R.GOLD_WALK));
test('step count distinct from Walking',()=>assert.notEqual(R.GOLD_STEPS,R.GOLD_WALK));
test('stairs distinct from Walking',()=>assert.notEqual(R.GOLD_STAIRS,R.GOLD_WALK));
test('review returns exactly five topics',()=>assert.equal(report.topics.length,5));
test('review not full catalog',()=>assert.equal(report.qualityGate.fullCatalogNegativeMatchesVerified,false));
test('review not live E2E',()=>assert.equal(report.qualityGate.liveDiagnosticsE2e,false));
test('review no SQL/API billed',()=>{assert.equal(report.sqlExecuted,false);assert.equal(report.paidApiCalls,0)});
test('review no invented IDs',()=>assert.equal(report.qualityGate.unapprovedTopicIdsInvented,false));
test('exact approval only one of five topics',()=>assert.equal(report.topics.filter(x=>x.approvedExactUuid!==null).length,1));
for(const topic of R.TOPICS){
 const key=topic.key;
 test(`${key}: finite approval decision`,()=>assert.equal(R.decision(gold,topic.text).status, key==='walking'?'OWNER_APPROVED_EXACT_ONLY':'NO_APPROVED_EXACT_IN_LIMITED_FIXTURE'));
 test(`${key}: candidate set remains 18`,()=>assert.equal(R.input(gold).lexical.length,18));
 test(`${key}: no duplicate candidate id`,()=>assert.equal(new Set(R.input(gold).lexical.map(x=>x.onId)).size,18));
 test(`${key}: ranker responds successfully`,()=>assert.equal(R.rank(gold,H,topic.text).ok,true));
 test(`${key}: no false exact boost without supplied evidence`,()=>assert.equal(R.rank(gold,H,topic.text,{evidence:[]}).candidates.every(x=>x.matchPriority===0),true));
 test(`${key}: wrong locale does not boost`,()=>assert.equal(R.rank(gold,H,topic.text,{evidence:[pending(topic,null,'canonical_title','de')]}).candidates.every(x=>x.matchPriority===0),true));
 test(`${key}: pending alias not promoted`,()=>assert.equal(R.rank(gold,H,topic.text,{evidence:[pending(topic,'pending')]}).candidates.every(x=>x.matchPriority===0),true));
 test(`${key}: revoked alias not promoted`,()=>assert.equal(R.rank(gold,H,topic.text,{evidence:[pending(topic,'revoked')]}).candidates.every(x=>x.matchPriority===0),true));
 test(`${key}: context/variant not exact-boosted`,()=>assert.equal(R.rank(gold,H,topic.variant).candidates.every(x=>x.matchPriority===0),true));
 test(`${key}: output explicitly limits coverage`,()=>assert.match(check(topic).coverage,/18_ON_GOLD|NOT_PROOF_OF_GLOBAL_ABSENCE/));
 test(`${key}: no graph expansion`,()=>assert.equal(R.rank(gold,H,topic.text).graphCandidatesAdded,0));
 test(`${key}: stable under reversed input at approval level`,()=>assert.equal(check(topic).sourcePermutationChecked,true));
}
