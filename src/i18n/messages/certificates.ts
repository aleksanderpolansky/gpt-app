export function isCertificateLocale(
  value: string | null | undefined
): value is CertificateLocale {
  return supportedCertificateLocales.includes(value as CertificateLocale);
}

export function getCertificatesMessages(
  locale: string | null | undefined
): CertificatesMessages {
  if (isCertificateLocale(locale)) {
    return certificatesMessages[locale];
  }

  return certificatesMessages[fallbackCertificateLocale];
}

export function getCertificateText(
  group: CertificateMessageGroup,
  key: string,
  fallback: string
) {
  const value = group[key];

  if (typeof value === "string" && value.trim().length > 0) {
    return value;
  }

  return fallback;
}
