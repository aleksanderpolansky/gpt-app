type GroupName = keyof CertificatesMessages;
type CertificateMessageOverrides = Partial<Record<GroupName, CertificateMessageGroup>>;

function mergeGroup(
  base: CertificateMessageGroup,
  override: CertificateMessageGroup | undefined
): CertificateMessageGroup {
  return { ...base, ...(override ?? {}) };
}

function mergeCertificateMessages(
  overrides: CertificateMessageOverrides
): CertificatesMessages {
  return {
    common: mergeGroup(enCertificateMessages.common, overrides.common),
    newPage: mergeGroup(enCertificateMessages.newPage, overrides.newPage),
    orderForm: mergeGroup(enCertificateMessages.orderForm, overrides.orderForm),
    redeemPage: mergeGroup(enCertificateMessages.redeemPage, overrides.redeemPage),
    myCertificates: mergeGroup(
      enCertificateMessages.myCertificates,
      overrides.myCertificates
    ),
    sellerCertificates: mergeGroup(
      enCertificateMessages.sellerCertificates,
      overrides.sellerCertificates
    ),
    actions: mergeGroup(enCertificateMessages.actions, overrides.actions),
  };
}

