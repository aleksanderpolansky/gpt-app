export function getDirectoryListMessage(
  key: DirectoryListMessageKey,
  locale: LocaleCode,
  params: DirectoryListMessageParams = {},
) {
  const messageByLocale = directoryListMessages[key];
  const template = messageByLocale[locale] ?? messageByLocale.en ?? key;

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, paramKey: string) => {
    const value = params[paramKey];

    if (value === null || typeof value === "undefined") {
      return "";
    }

    return String(value);
  });
}
